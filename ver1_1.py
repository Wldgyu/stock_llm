    def fetch_real_news(self, query):
        encoded_query = urllib.parse.quote(query)
        is_ko = any(ord(c) > 127 for c in query)
        url = f"https://news.google.com/rss/search?q={encoded_query}&hl={'ko&gl=KR&ceid=KR:ko' if is_ko else 'en-US&gl=US&ceid=US:en'}"
        rss = feedparser.parse(url)
        return [entry.title for entry in rss.entries[:5]]

    def fetch_data(self, symbol):
        df = yf.download(symbol, period="1y", interval="1d", progress=False)
        if df.empty: return None
        if isinstance(df.columns, pd.MultiIndex):
            df.columns = df.columns.get_level_values(0)
        return df.ffill()

    def get_sentiment(self, name):
        news_list = self.fetch_real_news(name)
        if not news_list: return 0.0
        is_ko = any(ord(c) > 127 for c in name)
        pipe = self.ko_pipe if is_ko else self.en_pipe

        scores = []
        for news in news_list:
            try:
                result = pipe(news[:512])[0]
                score = result['score']
                label = result['label'].upper()
                if label in ['NEGATIVE', 'LABEL_0']: score = -score
                elif label in ['NEUTRAL']: score *= 0.1
                scores.append(score)
            except: continue
        return sum(scores) / len(scores) if scores else 0.0

    def analyze(self, name, symbol):
        try:
            df = self.fetch_data(symbol)
            if df is None: return

            df['MA20'] = ta.sma(df['Close'], length=20)
            df['RSI'] = ta.rsi(df['Close'], length=14)
            bbands = ta.bbands(df['Close'], length=20, std=2)
            if bbands is not None:
                df = pd.concat([df, bbands], axis=1)

            high, low = float(df['High'].max()), float(df['Low'].min())

            # ✅ 해결 2: 변수명을 fib_618로 명확히 정의 (NameError 해결)
            fib_618 = high - (0.382 * (high - low))

            sentiment_score = self.get_sentiment(name)
            last_close = float(df['Close'].iloc[-1])
            prediction_price = last_close * (1 + (sentiment_score * 0.03))

            volatility = float(df['Close'].pct_change().std() * 100)
            risk_score = min(10, max(1, int(volatility * 5 + (1 - sentiment_score) * 2)))

            # ✅ 정의된 fib_618을 그대로 전달
            self.display_report(name, symbol, df, fib_618, sentiment_score, prediction_price, risk_score)

        except Exception as e:
            print(f"❌ {name} 분석 중 오류 발생: {e}")
            traceback.print_exc()


    def _send_request(self, persona_name, prompt, model_name):
        """서버 요청 공통 함수"""
        payload = {
            "model": model_name,
            "prompt": prompt,
            "stream": False,
            "options": {"temperature": 0.3},
            "keep_alive": "5s"
        }

        try:
            response = requests.post(self.url, json=payload, timeout=300)
            if response.status_code == 200:
                result_text = response.json().get("response", "").strip()
                return result_text
            else:
                print(f"      ❌ {persona_name} 서버 응답 오류 ({response.status_code})")
                return None
        except Exception as e:
            print(f"      ❌ {persona_name} API 호출 중 네트워크 예외 발생: {e}")
            return None
        finally:
            self.clear_vram_cache(model_name)

    def parse_score_from_response(self, text):
        """텍스트에서 최종 JSON 점수를 안정적으로 추출하는 헬퍼 함수"""
        if not text:
            return 0.0

        try:
            json_match = re.findall(r"\{.*?\}", text)
            if json_match:
                target_json = json_match[-1]
                data = json.loads(target_json)
                if "score" in data:
                    return float(data["score"])
        except Exception:
            pass

        try:
            if "score" in text.lower():
                scores = re.findall(r"[-+]?\d*\.\d+|\d+", text)
                if scores:
                    val = float(scores[-1])
                    if -1.0 <= val <= 1.0:
                        return val
        except Exception:
            pass

        return 0.0

